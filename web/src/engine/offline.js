// 用户画像提取
export function extractProfile(text, profile) {
  let liked = null
  let m = text.match(/(?:我(?:最)?(?:喜欢|爱吃|爱喝|最爱|好喜欢|爱听|爱看|超喜欢|真的很喜欢))\s*([^，。！？,.!?]{1,12})/)
  if (m) liked = m[1].replace(/的$/, '').trim()
  if (liked) {
    if (!profile.likes.includes(liked)) profile.likes.push(liked)
  }
  m = text.match(/(?:我叫|我是|我的名字叫)\s*([^\s，。！？,.!?]{1,8})/)
  if (m) profile.name = m[1]
  if (text.length > 8) profile.events.push(text.slice(0, 40))
  if (profile.events.length > 30) profile.events.shift()
  return profile
}

export function analyzeIntent(text) {
  const t = text.replace(/\s+/g, '')
  if (/再见|拜拜|晚安|去睡了|先忙|睡了|走了|回聊|下次见/.test(t)) return 'farewell'
  if (/你好|您好|哈喽|哈啰|hello|hi|嗨|在吗|早呀|早上好|晚上好|早安/.test(t)) return 'greeting'
  if (/(最近|今天|这几天|现在).*(怎么样|如何|好吗|咋样|怎样)/.test(t)) return 'howareyou'
  if (/(你)?(还好吗|好么|好吗|过得怎么样|最近怎么样|心情如何|心情好不好)/.test(t)) return 'howareyou'
  if (/你是谁|你叫什么|你多大了|你几岁|你是什么|介绍一下你|你从哪|你住哪/.test(t)) return 'whoareyou'
  if (/喜欢你|爱你|想你|抱抱|亲亲|想你了|好喜欢你/.test(t)) return 'love'
  if (/谢谢你|谢谢|感谢|多谢/.test(t)) return 'thanks'
  if (/难过|伤心|不开心|好烦|心烦|好累|委屈|想哭|哭了|压力|孤独|孤单|焦虑|失眠|难受|痛苦|绝望|分手/.test(t)) return 'sad'
  if (/好可爱|好漂亮|真好看|好厉害|真棒|真牛|好帅|好美|可爱死|夸你/.test(t)) return 'compliment'
  if (/太棒|好耶|哈哈|开心|高兴|超开心|太爽|赢啦|成功/.test(t)) return 'happy'
  if (/好饿|饿了|没吃|吃饭|干饭|吃的什么/.test(t)) return 'hungry'
  if (/无聊|没意思|好闲|好闷|干嘛呢|干点啥|干什么好/.test(t)) return 'bored'
  if (/(吗|呢|么)$|\?|？|为什么|怎么|什么|哪里|谁|何时|几岁|多少/.test(t)) return 'question'
  return 'generic'
}

function fill(tpl, ctx) {
  return tpl
    .replace(/\{name\}/g, ctx.userName)
    .replace(/\{char\}/g, ctx.charName)
    .replace(/\{kw\}/g, ctx.keyword)
    .replace(/\{time\}/g, ctx.timeText)
}

function timeGreeting() {
  const h = new Date().getHours()
  if (h < 5) return '夜深了'
  if (h < 9) return '早上好'
  if (h < 12) return '上午好'
  if (h < 14) return '中午好'
  if (h < 18) return '下午好'
  return '晚上好'
}

function extractKeyword(text) {
  const m = text.replace(/[，。！？,.!?\s]/g, '').match(/[\u4e00-\u9fa5a-zA-Z]{2,8}/g)
  if (!m) return ''
  return m[m.length - 1] || ''
}

// 生成回复
export function generateReply(character, history, profile) {
  const lastUser = [...history].reverse().find((m) => m.role === 'user')
  const text = lastUser ? lastUser.content : ''
  const intent = analyzeIntent(text)
  const ctx = {
    userName: profile.name || '朋友',
    charName: character.name,
    keyword: extractKeyword(text),
    timeText: timeGreeting(),
  }

  let pool = GENERIC
  const styleId = character.style
  if (T[styleId]) pool = T[styleId]

  // whoareyou 特殊处理：结合角色卡
  if (intent === 'whoareyou') {
    return character.persona ? character.persona.split(/[。\n]/)[0] + '。' : pick(pool.generic)
  }

  let reply = pick(pool[intent] || pool.generic)

  // 关键词回响（仅当有实质内容且非问句时）
  if (intent === 'generic' && ctx.keyword && ctx.keyword.length >= 2 && chance(0.5)) {
    reply = pick([
      `「${ctx.keyword}」吗？这个话题我喜欢，你多说点嘛。`,
      `说到${ctx.keyword}，我还挺感兴趣的，继续继续。`,
      `${ctx.keyword}啊…我听着呢，然后呢？`,
    ])
  }

  // 记忆回响：提到用户喜欢的东西
  if (profile.likes.length > 0 && chance(0.3)) {
    const like = pick(profile.likes)
    reply = pick([
      `对了，说到这个，我记得你好像挺喜欢${like}的？`,
      `你之前不是说喜欢${like}嘛，最近还有在玩吗？`,
      `说起来，${like}…那不是你喜欢的吗？`,
    ])
  }

  // 关怀问候（随机注入，增加真实感，不覆盖问候/道别/感谢）
  if (chance(0.18) && !['greeting', 'farewell', 'thanks'].includes(intent)) {
    reply = pick([
      `顺便问一句，你今天{time}吃饭了没？`,
      `对了，{name}，最近有没有好好休息呀？`,
      `说到这，我今天{time}的时候还想起你呢。`,
      `{name}，你今天心情如何？`,
    ])
  }
  reply = fill(reply, ctx)

  // 追加追问，保持对话
  if (!/(\?|？)$/.test(reply) && chance(0.65)) {
    reply += pick(pool.followup || GENERIC.followup)
  }
  return reply.replace(/\s+/g, ' ').trim()
}

export function formatHistoryForOffline(history, limit = 16) {
  return history.slice(-limit).map((m) => (m.role === 'user' ? '用户' : '角色') + '：' + m.content).join('\n')
}
